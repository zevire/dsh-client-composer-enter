#!/usr/bin/env node
/**
 * Regenerate this package's runtime artifacts from its sources.
 *
 * The browser artifact is the same lazy-factory shape the official dsh client
 * build emits:
 *
 *   window.__ModuleLoader__.load({ id, factory })
 *
 * `factory(require)` receives the shell's module table `require`, so a plugin may
 * require platform seed words (`react`, `react/jsx-runtime`, `react-dom`, ...)
 * without a bundler. `src/client/index.js` stays plain ESM: the two top-level
 * `export` keywords are stripped and the bindings are republished as
 * `exports.apply` / `exports.inject`.
 *
 * The host half is `src/index.js` when present (published verbatim behind a
 * generated header); a browser-only package gets the inert `export function
 * apply() {}` stub so the Loader still has a node-side row to import.
 *
 * Both artifacts are gated with `node --check`. No dependencies, no network.
 */
import { execFileSync } from 'node:child_process'
import { existsSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

const root = dirname(dirname(fileURLToPath(import.meta.url)))
const pkg = JSON.parse(readFileSync(join(root, 'package.json'), 'utf8'))
const name = pkg.name
if (typeof name !== 'string' || name === '') throw new Error('package.json declares no name')

// Strip the top-level `export` keywords; the factory publishes the bindings.
const sourcePath = join(root, 'src', 'client', 'index.js')
const bodyLines = readFileSync(sourcePath, 'utf8').split(/\r?\n/).map(line => line.replace(/^export\s+/, ''))
const body = bodyLines.join('\n')
for (const binding of ['function apply', 'const inject']) {
  if (!body.includes(binding)) throw new Error(`source must declare "${binding}": ${sourcePath}`)
}
const indented = bodyLines.map(line => (line === '' ? '' : `\t\t${line}`)).join('\n')

const HEADER = '// Generated by scripts/build.mjs from src/client/index.js — do not edit by hand.'
const client = `${HEADER}
window.__ModuleLoader__.load({
\tid: ${JSON.stringify(name)},
\tfactory: (require) => {
\t\tvar module = { exports: {} };
\t\tvar exports = module.exports;
\t\tObject.defineProperty(exports, Symbol.toStringTag, { value: "Module" });
${indented}
\t\texports.apply = apply;
\t\texports.inject = inject;
\t\treturn module.exports;
\t}
});`

// Host half: a real ESM module the Loader imports. A browser-only package keeps
// the inert stub so the node-side row resolves.
const hostSourcePath = join(root, 'src', 'index.js')
let host
let typesHost
if (existsSync(hostSourcePath)) {
  const hostLines = readFileSync(hostSourcePath, 'utf8').split(/\r?\n/)
  host = ['// Generated by scripts/build.mjs from src/index.js — do not edit by hand.', '', ...hostLines].join('\n')
  const declarations = []
  const text = hostLines.join('\n')
  if (/^export\s+const\s+name\b/m.test(text)) declarations.push('export declare const name: string')
  if (/^export\s+const\s+inject\b/m.test(text)) declarations.push('export declare const inject: readonly string[]')
  if (/^export\s+const\s+Config\b/m.test(text)) declarations.push('export declare const Config: unknown')
  if (/^export\s+function\s+apply\b/m.test(text)) declarations.push('export declare function apply(ctx: unknown, config?: unknown): void')
  if (declarations.length === 0) throw new Error(`src/index.js declares no host export: ${hostSourcePath}`)
  typesHost = [`/** Host half of ${name} (generated from src/index.js). */`, ...declarations].join('\n')
} else {
  host = `/**
 * Host half of ${name}. The empty apply gives the Loader a node-side row; the
 * browser half ships through the ./client export.
 */

/** Host plugin body — this package contributes browser behavior only. */
export function apply() {}`
  typesHost = `/** Host half of ${name}. */
export declare function apply(): void`
}

const typesClient = `/** Browser half of ${name}. */
export declare const inject: readonly string[]
/**
 * Mount this plugin's browser behavior for the plugin lifetime.
 * @param ctx - Client root context.
 */
export declare function apply(ctx: unknown): void`

// Write, then gate both JavaScript artifacts.
const libDir = join(root, 'lib')
const typesDir = join(libDir, 'types')
mkdirSync(join(typesDir, 'client'), { recursive: true })
const artifacts = [
  [join(libDir, 'client.js'), client],
  [join(libDir, 'index.js'), host],
  [join(typesDir, 'index.d.ts'), typesHost],
  [join(typesDir, 'client', 'index.d.ts'), typesClient],
]
for (const [file, text] of artifacts) writeFileSync(file, `${text.replace(/\s+$/, '')}\n`, 'utf8')
for (const file of [join(libDir, 'client.js'), join(libDir, 'index.js')]) {
  execFileSync(process.execPath, ['--check', file], { stdio: 'inherit' })
}

console.log(`[build] ${name} artifacts written:`)
for (const [file] of artifacts) console.log(`  ${file.slice(root.length + 1)}`)
